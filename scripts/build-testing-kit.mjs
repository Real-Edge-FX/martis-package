#!/usr/bin/env node
/**
 * Builds the test runtime of consumer extensions into `dist/testing/`
 * (v2.3.0, docs/testing-extensions.md):
 *
 * - `runtime/`: the development library build of `resources/js/testing/index.tsx`
 *   (`vite.testing.config.ts`), with `runtime/martis.css`;
 * - `testing.mjs`: the stable entry a consumer's Vitest config names;
 * - `vitest.mjs` + `vitest.d.mts`: `martisExtensionTestConfig()`;
 * - `versions.json`: the versions of the libraries the SPA bundles.
 *
 * `testing.d.mts` is written by `npm run build:types`. Usage:
 * `npm run build:testing` (`npm run build` runs it).
 */
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'vite'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'dist/testing')

/** The libraries the SPA bundles, whose versions a consumer may match. */
const LIBRARIES = ['react', 'react-dom', 'react-router', 'react-i18next', 'i18next', '@tanstack/react-query', '@phosphor-icons/react', 'primereact']

await build({ configFile: path.join(root, 'vite.testing.config.ts'), logLevel: 'warn' })

const lock = JSON.parse(await readFile(path.join(root, 'package-lock.json'), 'utf8'))
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const versions = { martis: pkg.version }
for (const name of LIBRARIES) {
  const version = lock.packages?.[`node_modules/${name}`]?.version
  if (typeof version !== 'string') {
    throw new Error(`build-testing-kit: package-lock.json has no version for ${name}`)
  }
  versions[name] = version
}

await mkdir(out, { recursive: true })
await writeFile(path.join(out, 'versions.json'), `${JSON.stringify(versions, null, 2)}\n`)
await writeFile(
  path.join(out, 'testing.mjs'),
  "// The Martis test runtime (docs/testing-extensions.md). Generated by `npm run build:testing`: do not edit.\nexport * from './runtime/index.mjs'\n",
)
await copyFile(path.join(root, 'resources/js/testing/vitest.mjs'), path.join(out, 'vitest.mjs'))
await copyFile(path.join(root, 'resources/js/testing/vitest.d.mts'), path.join(out, 'vitest.d.mts'))

console.log('wrote       dist/testing/')
