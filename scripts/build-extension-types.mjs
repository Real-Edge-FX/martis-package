#!/usr/bin/env node
/**
 * Generates the TypeScript declarations of the consumer-extension shims.
 *
 * A consumer extension imports `@martis/runtime`, `react-dom`,
 * `react-dom/client`, `react-router-dom`, `react-i18next` and `@tanstack/react-query`; its Vite
 * config sends each to a shim under `resources/js/martis-extensions/.shims/`
 * that re-exports the host's copy from `window.Martis.runtime`.
 * `martis:install` publishes a `<shim>.d.mts` next to each of those shims,
 * and the consumer's `tsconfig.extensions.json` maps the same specifiers to
 * them.
 *
 * Each type entry in `resources/js/extension-types/` is bundled into
 * `stubs/extensions/<shim>-shim.d.mts.stub` with rollup-plugin-dts. The
 * Martis types and the third-party types behind the shim exports are
 * inlined, since the consumer installs none of those libraries; only the
 * packages `martis:install` adds to the consumer stay imports (`react`,
 * `react-dom`, `@phosphor-icons/react`), except in the declarations of the
 * shim for that specifier (`react-dom`), which inline the host's: the
 * consumer's tsconfig sends the specifier to them. The runtime declarations
 * import the other shims' declarations as siblings.
 *
 * Usage: `npm run build:types` (`npm run build` runs it too), or
 * `npm run build:types -- --check` to fail when a committed stub is stale.
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { rollup } from 'rollup'
import { dts } from 'rollup-plugin-dts'
import ts from 'typescript'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/** Packages `martis:install` adds to the consumer's package.json (InstallCommand::STABLE_NPM_DEPS). */
const CONSUMER_PACKAGES = /^(?:react|react-dom|@phosphor-icons\/react)(?:\/|$)/

const SIBLINGS = {
  'react-dom': './react-dom.mjs',
  'react-dom/client': './react-dom-client.mjs',
  // The SPA imports React Router 7 as `react-router`; the runtime entry's
  // re-exports point at the `react-router-dom` shim's declarations.
  'react-router': './react-router-dom.mjs',
  'react-i18next': './react-i18next.mjs',
  '@tanstack/react-query': './tanstack-react-query.mjs',
  i18next: './i18next.mjs',
}

const SHIMS = [
  { name: 'runtime', specifier: '@martis/runtime', siblings: SIBLINGS },
  { name: 'react-dom', specifier: 'react-dom', siblings: {} },
  // v2.10.0: `react-dom/client`'s `createRoot` and `hydrateRoot`.
  { name: 'react-dom-client', specifier: 'react-dom/client', siblings: {} },
  { name: 'react-router-dom', specifier: 'react-router-dom', siblings: {} },
  { name: 'react-i18next', specifier: 'react-i18next', siblings: { i18next: './i18next.mjs' } },
  { name: 'tanstack-react-query', specifier: '@tanstack/react-query', siblings: {} },
  // Types only (v2.3.0): the i18next declarations the two entries above share.
  // No shim module goes with them, so the generic header would name one.
  {
    name: 'i18next',
    specifier: 'i18next',
    siblings: {},
    header: [
      '/**',
      " * Types only: the i18next declarations a consumer's `tsconfig.extensions.json`",
      ' * maps `i18next` to, shared by the declarations of `.shims/react-i18next.mjs`',
      ' * and `.shims/runtime.mjs`. No module goes with them, and an extension build',
      " * does not resolve `i18next`: import its types (`import type { i18n } from 'i18next'`)",
      ' * and reach the host instance through `useTranslation()`. A test that creates its',
      ' * own instance installs i18next as a dev dependency (docs/testing-extensions.md).',
      ' *',
      ' * Generated by `npm run build:types` in the martis/martis package from',
      ' * `resources/js/extension-types/i18next.ts`. Do not edit this file:',
      ' * refresh the shims and their declarations together with',
      ' * `php artisan vendor:publish --tag=martis-extension-shims --force`.',
      ' */',
      '',
    ].join('\n'),
  },
  // The test kit's declarations (v2.3.0), published in dist/, not as a shim.
  {
    name: 'testing',
    specifier: '@martis/testing',
    siblings: {},
    external: ['@tanstack/react-query'],
    out: 'dist/testing/testing.d.mts',
    header: [
      '/**',
      ' * Type declarations of the Martis test runtime, `dist/testing/testing.mjs`',
      " * (`@martis/testing`). Generated by `npm run build:types` in the martis/martis",
      ' * package from `resources/js/extension-types/testing.ts`. Do not edit this file.',
      ' * See docs/testing-extensions.md.',
      ' */',
      '',
    ].join('\n'),
  },
]

/** Every module a declaration file imports (import / export-from declarations and `import('...')` types). */
function importedModules(code) {
  const modules = new Set()
  const visit = (node) => {
    if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier && ts.isStringLiteral(node.moduleSpecifier)) {
      modules.add(node.moduleSpecifier.text)
    }
    if (ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument) && ts.isStringLiteral(node.argument.literal)) {
      modules.add(node.argument.literal.text)
    }
    ts.forEachChild(node, visit)
  }
  visit(ts.createSourceFile('shim.d.mts', code, ts.ScriptTarget.Latest, false, ts.ScriptKind.TS))

  return modules
}

function header({ name, specifier }) {
  return [
    '/**',
    ` * Type declarations for \`.shims/${name}.mjs\`, the module a Martis`,
    ` * consumer-extension build resolves \`${specifier}\` to.`,
    ' *',
    ' * Generated by `npm run build:types` in the martis/martis package from',
    ` * \`resources/js/extension-types/${name}.ts\`. Do not edit this file:`,
    ' * refresh the shims and their declarations together with',
    ' * `php artisan vendor:publish --tag=martis-extension-shims --force`.',
    ' */',
    '',
  ].join('\n')
}

async function generate(shim) {
  const siblings = new Set(Object.keys(shim.siblings))
  const bundle = await rollup({
    input: path.join(root, 'resources/js/extension-types', `${shim.name}.ts`),
    // A shim's own specifier is inlined even when the consumer installs
    // it: its tsconfig `paths` entry points back at these declarations.
    external: (id) => (CONSUMER_PACKAGES.test(id) && id !== shim.specifier) || siblings.has(id) || (shim.external ?? []).includes(id),
    plugins: [dts({ tsconfig: path.join(root, 'tsconfig.json'), respectExternal: true })],
    onwarn(warning) {
      // The library's own declarations import types from i18next that they
      // never use (a sibling the bundle keeps external): harmless, dropped.
      if (warning.code === 'UNUSED_EXTERNAL_IMPORT' && siblings.has(warning.exporter)) return
      throw new Error(`${shim.name}: ${warning.message}`)
    },
  })

  try {
    const { output } = await bundle.generate({ format: 'es', paths: shim.siblings })
    const code = output[0].code

    // Every import left in the declarations must resolve in a consumer app.
    const allowed = new Set([...Object.values(shim.siblings), ...(shim.external ?? [])])
    for (const specifier of importedModules(code)) {
      if (!CONSUMER_PACKAGES.test(specifier) && !allowed.has(specifier)) {
        throw new Error(`${shim.name}: the declarations import '${specifier}', which a consumer app does not install`)
      }
      if (specifier === shim.specifier) {
        throw new Error(`${shim.name}: the declarations import '${specifier}', which the consumer's tsconfig sends back to them`)
      }
    }

    // The kit's declarations sit next to the runtime's in a consumer program:
    // a `declare global` here would redeclare `Window.MartisConfig` with
    // another copy of its type. Type its props without the config shape.
    if (shim.out !== undefined && /\bdeclare global\b/.test(code)) {
      throw new Error(`${shim.name}: the declarations add a global augmentation; keep config.ts's types out of them`)
    }

    return (shim.header ?? header(shim)) + code
  } finally {
    await bundle.close()
  }
}

const check = process.argv.includes('--check')
const stale = []

for (const shim of SHIMS) {
  const relative = shim.out ?? `stubs/extensions/${shim.name}-shim.d.mts.stub`
  const file = path.join(root, relative)
  const generated = await generate(shim)
  const current = await readFile(file, 'utf8').catch(() => null)

  if (current === generated) {
    console.log(`up to date  ${relative}`)
  } else if (check) {
    stale.push(relative)
  } else {
    await writeFile(file, generated)
    console.log(`wrote       ${relative}`)
  }
}

if (stale.length > 0) {
  console.error(`Stale extension declarations, run \`npm run build:types\`:\n  ${stale.join('\n  ')}`)
  process.exit(1)
}
