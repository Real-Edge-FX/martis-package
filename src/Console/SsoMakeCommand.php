    /**
     * `martis:sso <audience> --issuer`: one audience of `auth.sso.issuer`.
     */
    protected function handleIssuer(): int
    {
        $audience = $this->providerArgument();
        $audience = ltrim((string) preg_replace('/[^a-z0-9._-]/', '-', $audience), '._-');

        if (preg_match('/\A'.IssuerSettings::AUDIENCE_PATTERN.'\z/', $audience) !== 1 || in_array($audience, ['callback', 'redirect'], true)) {
            $this->error('The audience must be 1 to 64 letters, digits, dots, dashes or underscores, start with a letter or digit, and not be "callback" or "redirect".');

            return self::INVALID;
        }

        $this->components->info("Scaffolding SSO issuer audience: {$audience}");

        $envName = strtoupper((string) preg_replace('/[^A-Za-z0-9]/', '_', $audience));
        $this->updateIssuerConfig($audience, $envName);
        $this->updateIssuerEnv($envName);

        $this->newLine();
        $this->line('<fg=cyan>Next:</>');
        $this->line('  1. <fg=cyan>php artisan martis:sso:keys</> prints a key pair and writes nothing. Put the SECRET key in this app\'s');
        $this->line('     environment as MARTIS_SSO_ISSUER_PRIVATE_KEY (never commit it); the PUBLIC key goes to the consuming app.');
        $this->line('  2. Fill MARTIS_SSO_ISSUER (this app\'s name in the token) and MARTIS_SSO_ISSUER_AUDIENCE_'.$envName.'_CALLBACK_URL');
        $this->line('     (the consuming app\'s /'.config('martis.path', 'martis').'/sso/<provider>/callback URL), then MARTIS_SSO_ISSUER_ENABLED=true.');
        $this->line('  3. The consuming app uses authorize_url '.url('/'.config('martis.path', 'martis')."/sso/issue/{$audience}").' and audience "'.$audience.'".');
        $this->newLine();

        return self::SUCCESS;
    }

    protected function updateIssuerConfig(string $audience, string $envName): void
    {
        $configPath = config_path('martis.php');
        if (! file_exists($configPath)) {
            $this->components->warn('config/martis.php not found — run php artisan martis:install first.');

            return;
        }

        $contents = (string) file_get_contents($configPath);
        $entry = "                '{$audience}' => ['callback_url' => env('MARTIS_SSO_ISSUER_AUDIENCE_{$envName}_CALLBACK_URL')],\n";

        // The `audiences` list of the issuer block: after the line `'issuer' => [`
        // of its own (not the comment or the `issuer` key inside it).
        $list = $this->issuerAudiencesList($contents);

        if ($list === null) {
            $this->components->warn('Could not find auth.sso.issuer.audiences in config/martis.php (publish the config again, or add the block). Paste this entry:');
            $this->line(rtrim($entry));

            return;
        }

        // Only the audiences list counts: a provider block, or any other key
        // of the file, named like the audience does not make it "declared".
        $body = substr($contents, $list['start'], $list['end'] - $list['start']);

        if ($this->isDeclared($body, $audience)) {
            $this->components->twoColumnDetail('<fg=yellow>Skipping</> config', "auth.sso.issuer.audiences.{$audience} already declared (edit manually)");

            return;
        }

        file_put_contents($configPath, substr_replace($contents, $entry, $list['start'], 0));
        $this->components->twoColumnDetail('<fg=green>Inserted</> config', "auth.sso.issuer.audiences.{$audience}");
    }

    /**
     * Where the content of the `audiences` list of the issuer block starts (the
     * line after its opening bracket) and where it ends (its closing bracket),
     * as offsets into `$contents`, or null when the file has no such list.
     * Brackets inside strings and `//` comments do not count.
     *
     * @return array{start: int, end: int}|null
     */
    protected function issuerAudiencesList(string $contents): ?array
    {
        if (preg_match('/^[ \t]*[\'"]issuer[\'"][ \t]*=>[ \t]*\[[ \t]*\n/m', $contents, $issuerBlock, PREG_OFFSET_CAPTURE) !== 1) {
            return null;
        }

        $from = $issuerBlock[0][1] + strlen($issuerBlock[0][0]);

        if (preg_match('/^[ \t]*[\'"]audiences[\'"][ \t]*=>[ \t]*\[[ \t]*\n/m', $contents, $list, PREG_OFFSET_CAPTURE, $from) !== 1) {
            return null;
        }

        $start = $list[0][1] + strlen($list[0][0]);
        $depth = 1;
        $quote = null;
        $length = strlen($contents);

        for ($i = $start; $i < $length; $i++) {
            $char = $contents[$i];

            if ($quote !== null) {
                if ($char === '\\') {
                    $i++;
                } elseif ($char === $quote) {
                    $quote = null;
                }

                continue;
            }

            if ($char === "'" || $char === '"') {
                $quote = $char;
            } elseif ($char === '/' && ($contents[$i + 1] ?? '') === '/') {
                $newline = strpos($contents, "\n", $i);
                $i = $newline === false ? $length : $newline;
            } elseif ($char === '[') {
                $depth++;
            } elseif ($char === ']' && --$depth === 0) {
                return ['start' => $start, 'end' => $i];
            }
        }

        return null;
    }

    protected function updateIssuerEnv(string $envName): void
    {
        // The private key line is an empty stub: the key is never generated or stored here.
        $entries = [
            'MARTIS_SSO_ISSUER_ENABLED' => 'false',
            'MARTIS_SSO_ISSUER' => '',
            'MARTIS_SSO_ISSUER_PRIVATE_KEY' => '',
            "MARTIS_SSO_ISSUER_AUDIENCE_{$envName}_CALLBACK_URL" => '',
        ];

        foreach ([base_path('.env'), base_path('.env.example')] as $envPath) {
            if (! file_exists($envPath)) {
                continue;
            }

            $contents = (string) file_get_contents($envPath);
            $changed = false;

            foreach ($entries as $key => $defaultValue) {
                if (! preg_match('/^'.preg_quote($key, '/').'=/m', $contents)) {
                    $contents .= "\n{$key}={$defaultValue}";
                    $changed = true;
                }
            }

            if ($changed) {
                file_put_contents($envPath, $contents);
                $this->components->twoColumnDetail('<fg=green>Updated</>', basename($envPath));
            }
        }
    }
